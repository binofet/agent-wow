using System.Text;
using System.Text.Json;
using Metagen;
using WarcraftBuddy.Behavior;

if (args.Length != 1) throw new ArgumentException("Pass a trusted output directory");
var source = ReflectionMetaSource.Load(typeof(Input).Assembly.Location);
var result = Generation.Run(source, [new Bindings()]);
if (result.Diagnostics.Any(d => d.Severity == DiagnosticSeverity.Error)) throw new InvalidDataException("Behavior schema generation failed");
foreach (var artifact in result.Artifacts) {
    var target = Path.Combine(Path.GetFullPath(args[0]), artifact.RelativePath);
    Directory.CreateDirectory(Path.GetDirectoryName(target)!);
    File.WriteAllBytes(target, artifact.Content.ToArray());
    Console.WriteLine(artifact.RelativePath);
}

sealed class Bindings : IMetaGenerator {
    public string Id => "warcraftbuddy.behavior.go-lua.v1";
    static IMetaAttribute Attr(IEnumerable<IMetaAttribute> rows, string name) => rows.Single(a => a.TypeName == "Metagen." + name);
    static string Text(object? value) => Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture) ?? "";
    public GenerationResult Generate(IMetaSource source) {
        var types = source.Types.Where(t => t.Attributes.Any(a => a.TypeName == "Metagen.MetaSchemaAttribute")).ToList();
        var names = types.ToDictionary(t => t.FullName, t => Text(Attr(t.Attributes,"MetaSchemaAttribute").Arguments[2].Value));
        string GoType(MetaTypeRef type) => type.Name switch {
            "System.String" => "string", "System.UInt32" => "uint32", "System.Double" => "float64",
            "System.Collections.Generic.List`1" when type.Arguments.Count == 1 => "[]" + GoType(type.Arguments[0]),
            _ => names.TryGetValue(type.Name, out var name) ? name : throw new InvalidDataException("Unsupported behavior field type: " + type.Name)
        };
        var go = new StringBuilder("// Code generated by Metagen consumer dev/behavior-schema. DO NOT EDIT.\npackage behaviorcontract\n\n");
        var lua = new StringBuilder("-- Generated by Metagen consumer dev/behavior-schema. DO NOT EDIT.\nlocal schema = {}\n");
        foreach (var type in types.OrderBy(t => names[t.FullName], StringComparer.Ordinal)) {
            var schema = Attr(type.Attributes,"MetaSchemaAttribute");
            var name = names[type.FullName];
            var fields = type.Members.Select(m => (Member:m, Attr:Attr(m.Attributes,"MetaFieldAttribute"))).OrderBy(f => Convert.ToUInt32(f.Attr.Arguments[0].Value)).ToList();
            if (fields.Select(f => Text(f.Attr.Arguments[0].Value)).Distinct().Count() != fields.Count) throw new InvalidDataException("Duplicate field ID");
            go.Append("const ").Append(name).Append("TypeID = ").Append(JsonSerializer.Serialize(Text(schema.Arguments[0].Value))).Append("\n");
            go.Append("type ").Append(name).Append(" struct {\n");
            lua.Append("schema.").Append(name).Append(" = { id = ").Append(JsonSerializer.Serialize(Text(schema.Arguments[0].Value))).Append(", version = ").Append(Text(schema.Arguments[1].Value)).Append(", fields = {\n");
            foreach (var field in fields) {
                var wireName = Text(field.Attr.Arguments[1].Value);
                go.Append('\t').Append(field.Member.Name).Append(' ').Append(GoType(field.Member.Type)).Append(" `json:\"").Append(wireName).Append("\"`\n");
                lua.Append("  [").Append(Text(field.Attr.Arguments[0].Value)).Append("] = { name = ").Append(JsonSerializer.Serialize(wireName)).Append(", type = ").Append(JsonSerializer.Serialize(GoType(field.Member.Type))).Append(" },\n");
            }
            go.Append("}\n\n");lua.Append("} }\n");
        }
        lua.Append("return schema\n");
        return new GenerationResult([new GeneratedArtifact("pkg/behaviorcontract/contracts_generated.go", "text/x-go", Encoding.UTF8.GetBytes(go.ToString())), new GeneratedArtifact("behaviors/contract_generated.lua", "text/x-lua", Encoding.UTF8.GetBytes(lua.ToString()))], []);
    }
}
